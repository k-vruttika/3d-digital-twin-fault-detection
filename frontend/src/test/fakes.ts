/** Label factory that records every texture (a tiny DataTexture) and the texts drawn. */
export function fakeLabels(): { factory: LabelTextureFactory; texts: string[]; textures: DataTexture[] } {
  const texts: string[] = [];
  const textures: DataTexture[] = [];
  const factory: LabelTextureFactory = (text) => {
    texts.push(text);
    const tex = new DataTexture(new Uint8Array(4), 1, 1, RGBAFormat);
    textures.push(tex);
    return { texture: tex, aspect: 4 };
  };
  return { factory, texts, textures };
}

/** A manual requestAnimationFrame. */
export class ManualFrames {
  private next = 1;
  readonly pending = new Map<number, (t: number) => void>();
  request = (cb: (t: number) => void): number => {
    const id = this.next++;
    this.pending.set(id, cb);
    return id;
  };
  cancel = (id: number): void => {
    this.pending.delete(id);
  };
  run(t: number): void {
    const cbs = [...this.pending.values()];
    this.pending.clear();
    for (const cb of cbs) cb(t);
  }
}

export interface TestEngine {
  engine: TwinEngine;
  container: FakeElement;
  renderer: FakeRenderer;
  controls: FakeControls;
  frames: ManualFrames;
  labels: ReturnType<typeof fakeLabels>;
  clock: { now: number };
}

export function createTestEngine(opts: Partial<TwinEngineOptions> = {}): TestEngine {
  const container = new FakeElement();
  const renderer = new FakeRenderer();
  const controls = new FakeControls();
  const frames = new ManualFrames();
  const labels = fakeLabels();
  const clock = { now: 0 };
  const engine = new TwinEngine(container as unknown as HTMLElement, {
    createRenderer: () => renderer,
    createControls: () => controls,
    labelTextureFactory: labels.factory,
    requestFrame: frames.request,
    cancelFrame: frames.cancel,
    now: () => clock.now,
    wallClock: () => Date.parse("2026-01-01T00:00:10Z"),
    devicePixelRatio: 1,
    ...opts,
  });
  return { engine, container, renderer, controls, frames, labels, clock };
}
