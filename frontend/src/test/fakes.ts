/** GET /line for config/line.yaml and config/line_single.yaml (generated by `poe api-docs`). */
export const LINE = lineJson as unknown as LineResponse;
export const LINE_SINGLE = lineSingleJson as unknown as LineResponse;

export function cloneLine(line: LineResponse = LINE): LineResponse {
  return JSON.parse(JSON.stringify(line)) as LineResponse;
}

export class FakeElement {
  readonly listeners = new Map<string, Set<EventListener>>();
  readonly children: FakeElement[] = [];
  readonly style: Record<string, string> = {};
  readonly dataset: Record<string, string> = {};
  parent: FakeElement | null = null;
  removed = false;

  constructor(
    public clientWidth = 800,
    public clientHeight = 600,
  ) {}

  addEventListener(type: string, fn: EventListener): void {
    let set = this.listeners.get(type);
    if (set === undefined) {
      set = new Set();
      this.listeners.set(type, set);
    }
    set.add(fn);
  }

  removeEventListener(type: string, fn: EventListener): void {
    this.listeners.get(type)?.delete(fn);
  }

  get listenerCount(): number {
    let n = 0;
    for (const set of this.listeners.values()) n += set.size;
    return n;
  }

  dispatch(type: string, ev: Record<string, unknown> = {}): void {
    for (const fn of [...(this.listeners.get(type) ?? [])]) fn(ev as unknown as Event);
  }

  appendChild(child: FakeElement): FakeElement {
    this.children.push(child);
    child.parent = this;
    return child;
  }

  remove(): void {
    if (this.parent !== null) {
      const i = this.parent.children.indexOf(this);
      if (i >= 0) this.parent.children.splice(i, 1);
    }
    this.parent = null;
    this.removed = true;
  }

  getBoundingClientRect(): { left: number; top: number; width: number; height: number } {
    return { left: 0, top: 0, width: this.clientWidth, height: this.clientHeight };
  }
}

